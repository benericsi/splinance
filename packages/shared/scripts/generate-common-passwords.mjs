// Regenerates src/password/common-passwords.ts from the zxcvbn-ts frequency list.
// Run: pnpm --filter @splinance/shared gen:common-passwords
import { writeFileSync } from 'node:fs';
import { dictionary } from '@zxcvbn-ts/language-common';
import { fileURLToPath } from 'node:url';

const MIN_LENGTH = 10; // Shorter ones already fail the length rule.
const COUNT = 1000;

const seen = new Set();
for (const password of dictionary['passwords-common']) {
  const normalized = password.toLowerCase();
  if (normalized.length >= MIN_LENGTH && normalized.length <= 128) seen.add(normalized);
  if (seen.size === COUNT) break;
}

const body = [...seen].map((p) => JSON.stringify(p)).join(',\n  ');
const out = `// Generated by scripts/generate-common-passwords.mjs. Do not edit by hand.
// Source: @zxcvbn-ts/language-common (MIT), the ${String(COUNT)} most frequent passwords
// with at least ${String(MIN_LENGTH)} characters, lowercased.
export const COMMON_PASSWORDS: ReadonlySet<string> = new Set([
  ${body},
]);
`;

writeFileSync(fileURLToPath(new URL('../src/password/common-passwords.ts', import.meta.url)), out);
console.log(`Wrote ${String(seen.size)} passwords`);
